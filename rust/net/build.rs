use std::path::{Path, PathBuf};

fn main() {
    let protos = [
        "src/proto/cds2.proto",
        "src/proto/chat_provisioning.proto",
        "src/proto/chat_websocket.proto",
        "src/proto/svr2.proto",
    ];
    prost_build::Config::new()
        .bytes([
            ".signal.proto.chat_provisioning",
            ".signal.proto.chat_websocket",
        ])
        .compile_protos(&protos, &["src"])
        .expect("Protobufs in src are valid");
    for proto in &protos {
        println!("cargo:rerun-if-changed={proto}");
    }

    swarm_root_certificates();
}

/// The file names, relative to `res/swarm/`, of the DER-encoded roots that are always trusted for
/// SWARM services.
///
/// These are the public Let's Encrypt (Internet Security Research Group) roots: the two roots in
/// every OS trust store today (`isrg-root-x1.cer`, `isrg-root-x2.cer`), plus Let's Encrypt's
/// next-generation roots (`isrg-root-ye.cer`, `isrg-root-yr.cer`, published at
/// <https://letsencrypt.org/certificates/> as "ISRG Root YE" / "ISRG Root YR", not yet in OS trust
/// stores but already cross-signed into some issuance chains). Pinning them now, before an OS trust
/// store carries them, means a future chain that no longer cross-signs through X1/X2 still
/// validates. Signal's own roots are deliberately *not* here.
const SWARM_BUILTIN_ROOT_DERS: &[&str] = &[
    "isrg-root-x1.cer",
    "isrg-root-x2.cer",
    "isrg-root-ye.cer",
    "isrg-root-yr.cer",
];

/// Name of the environment variable holding the path of an optional extra PEM file.
const EXTRA_ROOT_CA_PEM_VAR: &str = "SWARM_TLS_ROOT_CA_PEM";

/// Writes `$OUT_DIR/swarm_root_ca_ders.rs`, which defines
/// `SWARM_ROOT_CA_DERS: &[&[u8]]`: the built-in public roots above, plus every certificate in
/// the PEM file named by `$SWARM_TLS_ROOT_CA_PEM` (or `res/swarm/swarm-root-ca.pem` when that
/// file exists), in that order.
///
/// A private SWARM root is therefore *added to*, never substituted for, the public roots, and a
/// build with no extra file configured trusts exactly the public Let's Encrypt roots.
fn swarm_root_certificates() {
    println!("cargo:rerun-if-env-changed={EXTRA_ROOT_CA_PEM_VAR}");

    let manifest_dir = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("set by cargo"));
    let out_dir = PathBuf::from(std::env::var("OUT_DIR").expect("set by cargo"));
    let res_dir = manifest_dir.join("res").join("swarm");

    let mut includes = Vec::new();

    for name in SWARM_BUILTIN_ROOT_DERS {
        let path = res_dir.join(name);
        assert!(
            path.exists(),
            "missing built-in SWARM root certificate {}",
            path.display()
        );
        println!("cargo:rerun-if-changed={}", path.display());
        includes.push(include_bytes_literal(&path));
    }

    let default_extra_pem = res_dir.join("swarm-root-ca.pem");
    println!("cargo:rerun-if-changed={}", default_extra_pem.display());
    let extra_pem = match std::env::var(EXTRA_ROOT_CA_PEM_VAR) {
        Ok(path) if !path.trim().is_empty() => {
            let path = PathBuf::from(path.trim());
            println!("cargo:rerun-if-changed={}", path.display());
            assert!(
                path.exists(),
                "{EXTRA_ROOT_CA_PEM_VAR} points at {} which does not exist",
                path.display()
            );
            Some(path)
        }
        _ => default_extra_pem.exists().then_some(default_extra_pem),
    };

    if let Some(pem_path) = &extra_pem {
        let pem = std::fs::read_to_string(pem_path)
            .unwrap_or_else(|e| panic!("cannot read {}: {e}", pem_path.display()));
        let ders = pem_certificates_to_ders(&pem);
        assert!(
            !ders.is_empty(),
            "no CERTIFICATE block found in {}",
            pem_path.display()
        );
        for (i, der) in ders.iter().enumerate() {
            let out_path = out_dir.join(format!("swarm-extra-root-{i}.der"));
            std::fs::write(&out_path, der).expect("can write to OUT_DIR");
            includes.push(include_bytes_literal(&out_path));
        }
        println!(
            "cargo:warning=SWARM: trusting {} extra root certificate(s) from {}",
            ders.len(),
            pem_path.display()
        );
    }

    let generated = format!(
        "// @generated by rust/net/build.rs; do not edit.\n\
         pub(crate) const SWARM_ROOT_CA_DERS: &[&[u8]] = &[\n{}];\n",
        includes
            .iter()
            .map(|literal| format!("    {literal},\n"))
            .collect::<String>()
    );
    std::fs::write(out_dir.join("swarm_root_ca_ders.rs"), generated).expect("can write to OUT_DIR");
}

/// Renders `include_bytes!("...")` for `path`, using forward slashes (accepted on every host,
/// including Windows) so the literal needs no escaping.
fn include_bytes_literal(path: &Path) -> String {
    let path = path.to_str().expect("path is UTF-8").replace('\\', "/");
    assert!(
        !path.contains('"'),
        "path {path} cannot be used in a string literal"
    );
    format!("include_bytes!(\"{path}\")")
}

/// Extracts the DER bytes of every `CERTIFICATE` block in a PEM document.
///
/// Implemented here, rather than with a crate, to avoid adding a build dependency for thirty
/// lines of base64.
fn pem_certificates_to_ders(pem: &str) -> Vec<Vec<u8>> {
    const BEGIN: &str = "-----BEGIN CERTIFICATE-----";
    const END: &str = "-----END CERTIFICATE-----";

    let mut ders = Vec::new();
    let mut body: Option<String> = None;
    for line in pem.lines() {
        let line = line.trim();
        match (line, &mut body) {
            (BEGIN, _) => body = Some(String::new()),
            (END, Some(collected)) => {
                ders.push(base64_decode(collected).expect("valid base64 in PEM file"));
                body = None;
            }
            (_, Some(collected)) => collected.push_str(line),
            (_, None) => (),
        }
    }
    assert!(body.is_none(), "unterminated CERTIFICATE block in PEM file");
    ders
}

/// Decodes standard base64 (with optional `=` padding), rejecting anything else.
fn base64_decode(input: &str) -> Option<Vec<u8>> {
    const ALPHABET: &[u8; 64] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";

    let mut out = Vec::with_capacity(input.len() / 4 * 3);
    let mut accumulator: u32 = 0;
    let mut bits = 0u32;
    for byte in input.bytes() {
        if byte == b'=' || byte.is_ascii_whitespace() {
            continue;
        }
        let value = ALPHABET.iter().position(|c| *c == byte)?;
        accumulator = (accumulator << 6) | u32::try_from(value).expect("index of 64-byte array");
        bits += 6;
        if bits >= 8 {
            bits -= 8;
            out.push(u8::try_from((accumulator >> bits) & 0xff).expect("masked to a byte"));
        }
    }
    Some(out)
}
