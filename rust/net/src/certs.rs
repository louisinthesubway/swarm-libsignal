pub use libsignal_net_infra::certs::RootCertificates;

pub const SIGNAL_ROOT_CERTIFICATES: RootCertificates = RootCertificates::FromStaticDers(&[
    // Signal Messenger root, valid through 2032-01-24.
    include_bytes!("../res/signal.cer"),
    // Signal Messenger Ed25519 root, valid through 2036-06-16.
    include_bytes!("../res/signal-ed25519.cer"),
]);

// GIAG2 cert plus root certs from pki.goog
pub const PROXY_G_ROOT_CERTIFICATES: RootCertificates = RootCertificates::FromStaticDers(&[
    include_bytes!("../res/GIAG2.cer"),
    include_bytes!("../res/GSR2.cer"),
    include_bytes!("../res/GSR4.cer"),
    include_bytes!("../res/GTSR1.cer"),
    include_bytes!("../res/GTSR2.cer"),
    include_bytes!("../res/GTSR3.cer"),
    include_bytes!("../res/GTSR4.cer"),
]);

// SWARM modification (see docs/SWARM-CHANGES.md).
//
// `SWARM_ROOT_CA_DERS` is generated by `build.rs`: the four public Let's Encrypt (ISRG) roots
// shipped in `res/swarm/` (the two in every OS trust store today, X1/X2, plus the two
// next-generation roots, YE/YR, pinned ahead of OS trust-store adoption), followed by every
// certificate in the optional build-time PEM file named by `$SWARM_TLS_ROOT_CA_PEM` (or
// `res/swarm/swarm-root-ca.pem`).
include!(concat!(env!("OUT_DIR"), "/swarm_root_ca_ders.rs"));

/// Root certificates trusted when connecting to SWARM services.
///
/// This deliberately does **not** include Signal's roots: a SWARM build must not be able to
/// validate a connection to Signal's infrastructure. It trusts the public Let's Encrypt roots, so
/// an ordinary publicly issued certificate for a `swarm.green` host works, plus any private SWARM
/// root compiled in at build time.
pub const SWARM_ROOT_CERTIFICATES: RootCertificates =
    RootCertificates::FromStaticDers(SWARM_ROOT_CA_DERS);

/// An empty trust store, used for services an environment does not deploy.
///
/// Verification against it always fails, so a connection attempt to such a service cannot succeed
/// even if its (unresolvable) hostname somehow resolved.
pub const NO_ROOT_CERTIFICATES: RootCertificates = RootCertificates::FromStaticDers(&[]);

#[cfg(test)]
mod test {
    use sha2::{Digest as _, Sha256};

    use super::*;

    /// The published SHA-256 fingerprints of the Let's Encrypt roots, so that a future change
    /// cannot quietly substitute a different certificate authority.
    ///
    /// Fetched from <https://letsencrypt.org/certificates/> and hashed independently (not copied
    /// from any changelog) when each root was added.
    const ISRG_ROOT_X1_SHA256: &str =
        "96bcec06264976f37460779acf28c5a7cfe8a3c0aae11a8ffcee05c0bddf08c6";
    const ISRG_ROOT_X2_SHA256: &str =
        "69729b8e15a86efc177a57afb7171dfc64add28c2fca8cf1507e34453ccb1470";
    /// "ISRG Root YE" (ECDSA P-384, self-signed, generated 2025-09-03). Let's Encrypt's
    /// next-generation root, not yet in OS trust stores as of this writing.
    const ISRG_ROOT_YE_SHA256: &str =
        "e14ffcad5b0025731006caa43a121a22d8e9700f4fb9cf852f02a708aa5d5666";
    /// "ISRG Root YR" (RSA 4096, self-signed, generated 2025-09-03). Let's Encrypt's
    /// next-generation root, not yet in OS trust stores as of this writing.
    const ISRG_ROOT_YR_SHA256: &str =
        "e57b7e6f150c419102e8d5c055729ff967b9d1a829bf00cec89ca604ebf4a86f";

    fn sha256_hex(bytes: &[u8]) -> String {
        hex::encode(Sha256::digest(bytes))
    }

    #[test]
    fn swarm_roots_start_with_the_public_lets_encrypt_roots() {
        assert!(
            SWARM_ROOT_CA_DERS.len() >= 4,
            "expected at least the four built-in roots (X1, X2, YE, YR)"
        );
        assert_eq!(sha256_hex(SWARM_ROOT_CA_DERS[0]), ISRG_ROOT_X1_SHA256);
        assert_eq!(sha256_hex(SWARM_ROOT_CA_DERS[1]), ISRG_ROOT_X2_SHA256);
        assert_eq!(sha256_hex(SWARM_ROOT_CA_DERS[2]), ISRG_ROOT_YE_SHA256);
        assert_eq!(sha256_hex(SWARM_ROOT_CA_DERS[3]), ISRG_ROOT_YR_SHA256);
    }

    #[test]
    fn swarm_roots_parse_with_the_expected_subject() {
        use boring_signal::nid::Nid;

        // Every pinned root must be self-signed by ISRG (Internet Security Research Group), never
        // a substitute CA quietly introduced by a bad merge or a compromised build input. The two
        // older roots spell out the full name; the newer generation abbreviates it to "ISRG".
        const KNOWN_ORGANIZATIONS: &[&str] =
            &["Internet Security Research Group", "ISRG"];

        for der in SWARM_ROOT_CA_DERS {
            let cert = boring_signal::x509::X509::from_der(der).expect("valid DER certificate");
            let organization = cert
                .subject_name()
                .entries_by_nid(Nid::ORGANIZATIONNAME)
                .next()
                .expect("pinned root has an Organization Name")
                .data()
                .as_utf8()
                .expect("utf8")
                .to_string();
            assert!(
                KNOWN_ORGANIZATIONS.contains(&organization.as_str()),
                "unexpected Organization for a pinned SWARM root: {organization}"
            );
        }
    }

    #[test]
    fn swarm_roots_do_not_include_signal_roots() {
        let signal_roots: Vec<String> = [
            &include_bytes!("../res/signal.cer")[..],
            &include_bytes!("../res/signal-ed25519.cer")[..],
        ]
        .into_iter()
        .map(sha256_hex)
        .collect();
        for der in SWARM_ROOT_CA_DERS {
            assert!(
                !signal_roots.contains(&sha256_hex(der)),
                "a Signal root certificate is trusted by the SWARM environment"
            );
        }
    }

    #[test]
    fn swarm_roots_parse_as_certificates() {
        for der in SWARM_ROOT_CA_DERS {
            boring_signal::x509::X509::from_der(der).expect("valid DER certificate");
        }
    }
}
